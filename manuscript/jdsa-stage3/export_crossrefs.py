"""Export stable companion-label source dependencies, not temporary .aux files.

The journal can compile either primary document independently. Clean paired builds
prefer freshly generated .aux labels and refresh these small fallback sources.
"""
from pathlib import Path
import re
import sys

MAIN = 'Retrieval_Assisted_Scalar_Grounding_for_Natural_Language_Optimization_A_Diagnostic_Study.pdf'
SUPPLEMENT = 'ESM_1_Retrieval_Assisted_Scalar_Grounding_Supplement.pdf'


def export(build, output):
    for stem, prefix, pdf in [('main', 'M-', MAIN), ('supplement', 'S-', SUPPLEMENT)]:
        labels = []
        for line in (build / (stem + '.aux')).read_text().splitlines():
            match = re.fullmatch(r'\\newlabel\{([^}]+)\}\{(.*)\}', line)
            if match:
                key, fields = match.groups()
                if not fields.endswith('{}'):
                    raise ValueError('Unexpected external-label structure: ' + key)
                labels.append('\\newlabel{' + prefix + key + '}{' + fields[:-2] + '{' + pdf + '}}')
        if not labels:
            raise ValueError('No labels for ' + stem)
        (output / (stem + '_crossrefs.tex')).write_text(
            '% Companion reference definitions for independent journal compilation.\n'
            '% Regenerated by build.sh; preserve alongside the matching PDFs.\n' + '\n'.join(labels) + '\n')


if __name__ == '__main__':
    export(*map(Path, sys.argv[1:3]))
